int win_entry_c(void) {
    static char argv_buf[4][256];
    char *argv_ptrs[4] = { argv_buf[0], argv_buf[1], argv_buf[2], argv_buf[3] };
    const char *cmd = __imp_GetCommandLineA();
    int argc = parse_win_cmdline(cmd, argv_buf);
    return main_app(argc, argv_ptrs);
}

__attribute__((naked)) void _start(void) {
    __asm__ volatile (
        "andq $-16, %rsp\n\t"
        "subq $32, %rsp\n\t"
        "call win_entry_c\n\t"
        "movl %eax, %ecx\n\t"
        "call *__imp_ExitProcess(%rip)\n\t"
    );
}
