/* ---------------- Stage 1: Text Tokenizer & Semantic Latent Encoder ---------------- */

static unsigned int fnv1a_hash(const char *str) {
    unsigned int h = 2166136261U;
    while (*str) {
        char c = *str++;
        if (c >= 'A' && c <= 'Z') c += 32;
        h ^= (unsigned int)(unsigned char)c;
        h *= 16777619U;
    }
    return h;
}

static int is_stopword(const char *w) {
    return (my_streq_nocase(w, "a") || my_streq_nocase(w, "an") ||
            my_streq_nocase(w, "the") || my_streq_nocase(w, "of") ||
            my_streq_nocase(w, "in") || my_streq_nocase(w, "on") ||
            my_streq_nocase(w, "at") || my_streq_nocase(w, "with") ||
            my_streq_nocase(w, "and") || my_streq_nocase(w, "over") ||
            my_streq_nocase(w, "under") || my_streq_nocase(w, "by") ||
            my_streq_nocase(w, "to") || my_streq_nocase(w, "for"));
}

static void encode_text_prompt(const char *prompt, unsigned int user_seed, float z[EMB_DIM], unsigned int *out_seed) {
    for (int d = 0; d < EMB_DIM; d++) z[d] = 0.0f;

    unsigned int prompt_hash = fnv1a_hash(prompt) ^ (user_seed * 2654435761U);
    *out_seed = prompt_hash ? prompt_hash : 1337U;

    int matched_tokens = 0;
    int oov_tokens = 0;
    float oov_vec[EMB_DIM];
    for (int d = 0; d < EMB_DIM; d++) oov_vec[d] = 0.0f;

    int i = 0;
    char word[32];
    while (prompt[i]) {
        while (prompt[i] && !((prompt[i] >= 'a' && prompt[i] <= 'z') ||
                              (prompt[i] >= 'A' && prompt[i] <= 'Z') ||
                              (prompt[i] >= '0' && prompt[i] <= '9'))) {
            i++;
        }
        if (!prompt[i]) break;
        int wlen = 0;
        while (prompt[i] && ((prompt[i] >= 'a' && prompt[i] <= 'z') ||
                             (prompt[i] >= 'A' && prompt[i] <= 'Z') ||
                             (prompt[i] >= '0' && prompt[i] <= '9'))) {
            if (wlen < 31) {
                char c = prompt[i];
                if (c >= 'A' && c <= 'Z') c += 32;
                word[wlen++] = c;
            }
            i++;
        }
        word[wlen] = '\0';
        if (wlen == 0 || is_stopword(word)) continue;

        int found = -1;
        for (int v = 0; v < g_vocab_count; v++) {
            if (my_streq_nocase(word, g_vocab[v].word)) {
                found = v;
                break;
            }
        }
        if (found < 0 && wlen > 3 && word[wlen - 1] == 's') {
            char singular[32];
            my_strcpy(singular, word, 32);
            singular[wlen - 1] = '\0';
            for (int v = 0; v < g_vocab_count; v++) {
                if (my_streq_nocase(singular, g_vocab[v].word)) {
                    found = v;
                    break;
                }
            }
        }

        if (found >= 0) {
            for (int d = 0; d < EMB_DIM; d++) {
                z[d] += g_vocab[found].vec[d];
            }
            matched_tokens++;
        } else {
            unsigned int wh = fnv1a_hash(word);
            for (int d = 0; d < EMB_DIM; d++) {
                wh = wh * 1664525U + 1013904223U;
                float r = (float)((wh >> 8) & 0xFFFF) / 32768.0f - 1.0f;
                oov_vec[d] += r * 0.45f;
            }
            oov_tokens++;
        }
    }

    if (matched_tokens > 0) {
        float inv = 1.0f / my_sqrtf((float)matched_tokens);
        for (int d = 0; d < EMB_DIM; d++) {
            if (d < 5) {
                z[d] = my_clampf(z[d] * inv + (oov_tokens > 0 ? oov_vec[d] * 0.15f : 0.0f), -1.0f, 1.0f);
            } else {
                z[d] = my_clampf(z[d] * 0.75f + (oov_tokens > 0 ? my_fabsf(oov_vec[d]) * 0.2f : 0.0f), 0.0f, 1.0f);
            }
        }
    } else {
        unsigned int h = *out_seed;
        for (int d = 0; d < EMB_DIM; d++) {
            h = h * 1664525U + 1013904223U;
            float r = (float)((h >> 8) & 0xFFFF) / 65535.0f;
            z[d] = (d < 5) ? (r * 2.0f - 1.0f) : r;
        }
        z[5] = 0.7f;
        z[7] = 0.6f;
        z[9] = 0.75f;
    }
}

/* ---------------- Stage 2: 2D Value Noise & Fractional Brownian Motion (fBm) ---------------- */

static float hash2d(int x, int y, unsigned int seed) {
    unsigned int n = (unsigned int)(x * 374761393 + y * 668265263) ^ (seed * 1442695041U);
    n = (n ^ (n >> 13)) * 1274126177U;
    return (float)((n ^ (n >> 16)) & 0x7FFFFF) / (float)0x7FFFFF;
}

static float noise2d(float x, float y, unsigned int seed) {
    int ix = (int)my_floorf(x);
    int iy = (int)my_floorf(y);
    float fx = x - (float)ix;
    float fy = y - (float)iy;
    float ux = fx * fx * (3.0f - 2.0f * fx);
    float uy = fy * fy * (3.0f - 2.0f * fy);

    float a = hash2d(ix,     iy,     seed);
    float b = hash2d(ix + 1, iy,     seed);
    float c = hash2d(ix,     iy + 1, seed);
    float d = hash2d(ix + 1, iy + 1, seed);

    return a + (b - a) * ux + (c - a) * uy + (a - b - c + d) * ux * uy;
}

static float fbm2d(float x, float y, int octaves, float roughness, unsigned int seed) {
    float val = 0.0f;
    float amp = 0.5f;
    float freq = 1.0f;
    float norm = 0.0f;
    float gain = 0.42f + 0.18f * roughness;
    for (int i = 0; i < octaves; i++) {
        val += amp * noise2d(x * freq, y * freq, seed + (unsigned int)(i * 101));
        norm += amp;
        freq *= 2.03f;
        amp *= gain;
    }
    return val / (norm + 1e-6f);
}

/* ---------------- Stage 3: Neural Field Forward Pass (CPPN) ---------------- */

static void eval_neural_field(float nx, float ny, const float z[EMB_DIM], float out[OUT_DIM]) {
    float r = my_sqrtf(nx * nx + ny * ny);
    float in_vec[IN_DIM];
    in_vec[0] = nx;
    in_vec[1] = ny;
    in_vec[2] = r;
    in_vec[3] = my_sinf(nx * 3.14159f);
    in_vec[4] = my_cosf(ny * 3.14159f);
    in_vec[5] = my_sinf((nx + ny) * 6.28318f);
    in_vec[6] = my_cosf((nx - ny) * 6.28318f);
    in_vec[7] = my_sinf(r * 9.42477f);
    for (int d = 0; d < EMB_DIM; d++) {
        in_vec[8 + d] = z[d];
    }

    float h1[HID_DIM];
    for (int i = 0; i < HID_DIM; i++) {
        float sum = g_b1[i];
        for (int j = 0; j < IN_DIM; j++) {
            sum += g_W1[i][j] * in_vec[j];
        }
        h1[i] = my_tanhf(sum);
    }

    float h2[HID_DIM];
    for (int i = 0; i < HID_DIM; i++) {
        float sum = g_b2[i];
        for (int j = 0; j < HID_DIM; j++) {
            sum += g_W2[i][j] * h1[j];
        }
        h2[i] = my_tanhf(sum + 0.35f * h1[i]);
    }

    for (int c = 0; c < OUT_DIM; c++) {
        float sum = g_b3[c];
        for (int j = 0; j < HID_DIM; j++) {
            sum += g_W3[c][j] * h2[j];
        }
        out[c] = my_tanhf(sum);
    }
}

/* ---------------- Stage 4: Full Latent-Conditioned Scene Synthesizer ---------------- */

static void render_image(const float z[EMB_DIM], unsigned int seed) {
    float warmth     = z[0];
    float brightness = z[1];
    float red_acc    = z[2];
    float grn_acc    = z[3];
    float blu_acc    = z[4];
    float mtn_amt    = z[5];
    float city_amt   = z[6];
    float water_amt  = z[7];
    float forest_amt = z[8];
    float orb_amt    = z[9];
    float stars_amt  = z[10];
    float neon_amt   = z[11];
    float cloud_amt  = z[12];
    float grid_amt   = z[13];
    float abst_amt   = z[14];
    float roughness  = z[15];

    float horizon_y = (water_amt > 0.35f || grid_amt > 0.35f) ? 0.66f : 0.76f;
    if (abst_amt > 0.85f && mtn_amt < 0.2f && city_amt < 0.2f) {
        horizon_y = 1.05f;
    }

    float orb_x = 0.50f + 0.22f * my_sinf((float)(seed & 0xFF) * 0.07f);
    if (grid_amt > 0.4f || city_amt > 0.5f) orb_x = 0.50f;
    float orb_y = horizon_y - 0.22f - 0.10f * my_clampf(brightness + 0.5f, 0.0f, 1.0f);
    float orb_rad = 0.09f + 0.11f * orb_amt;

    float zen_r = my_clampf(0.08f + 0.18f * brightness + 0.22f * warmth + 0.20f * red_acc, 0.02f, 0.95f);
    float zen_g = my_clampf(0.10f + 0.28f * brightness + 0.15f * grn_acc, 0.02f, 0.95f);
    float zen_b = my_clampf(0.28f + 0.35f * brightness - 0.15f * warmth + 0.35f * blu_acc, 0.05f, 0.98f);

    float hor_r = my_clampf(0.35f + 0.35f * warmth + 0.25f * brightness + 0.30f * red_acc + 0.25f * neon_amt, 0.05f, 1.0f);
    float hor_g = my_clampf(0.25f + 0.15f * warmth + 0.30f * brightness + 0.25f * grn_acc, 0.04f, 0.98f);
    float hor_b = my_clampf(0.35f - 0.20f * warmth + 0.25f * brightness + 0.35f * blu_acc + 0.30f * neon_amt, 0.08f, 1.0f);

    static float mtn_h1[IMG_W];
    static float mtn_h2[IMG_W];
    static float city_h[IMG_W];
    static int   city_bldg_id[IMG_W];
    static float tree_h[IMG_W];

    for (int x = 0; x < IMG_W; x++) {
        float u = (float)x / (float)IMG_W;
        float n1 = fbm2d(u * 2.4f + 1.3f, 0.5f, 5, 0.45f, seed + 11);
        float n1_detail = fbm2d(u * 9.0f + 2.1f, 1.2f, 3, 0.5f, seed + 19);
        float env1 = 0.65f + 0.35f * my_sinf(u * 3.14159f);
        mtn_h1[x] = horizon_y - mtn_amt * env1 * (0.10f + 0.28f * n1 + 0.04f * n1_detail);

        float n2 = fbm2d(u * 3.6f + 7.7f, 1.5f, 4, 0.45f, seed + 29);
        float n2_detail = fbm2d(u * 11.0f + 4.3f, 2.3f, 3, 0.5f, seed + 37);
        mtn_h2[x] = horizon_y - mtn_amt * (0.04f + 0.16f * n2 + 0.025f * n2_detail);

        int col = (int)(u * 38.0f);
        city_bldg_id[x] = col;
        float bh = hash2d(col, 13, seed + 53);
        float bh2 = hash2d(col * 2 + (int)(u * 76.0f), 29, seed + 71);
        float center_boost = 1.0f - 0.55f * my_fabsf(u * 2.0f - 1.0f);
        float h_val = city_amt * center_boost * (0.06f + 0.28f * bh * bh + 0.06f * (bh2 > 0.7f ? 1.0f : 0.0f));
        float b_frac = u * 38.0f - (float)col;
        if (b_frac < 0.08f || b_frac > 0.94f) h_val *= 0.25f;
        city_h[x] = horizon_y - h_val;

        float tn = fbm2d(u * 45.0f, 3.1f, 3, 0.8f, seed + 97);
        float spire = my_fabsf(my_fmodf(u * 95.0f, 1.0f) * 2.0f - 1.0f);
        tree_h[x] = horizon_y - forest_amt * (0.03f + 0.09f * tn + 0.045f * (1.0f - spire));
    }

    #define NF_GRID 64
    static float nf_grid[NF_GRID + 1][NF_GRID + 1][OUT_DIM];
    for (int gy = 0; gy <= NF_GRID; gy++) {
        float ny = ((float)gy / (float)NF_GRID) * 2.0f - 1.0f;
        for (int gx = 0; gx <= NF_GRID; gx++) {
            float nx = ((float)gx / (float)NF_GRID) * 2.0f - 1.0f;
            eval_neural_field(nx, ny, z, nf_grid[gy][gx]);
        }
    }

    print_str("  Rendering 512x512 neural canvas: [");
    for (int y = 0; y < IMG_H; y++) {
        if ((y & 31) == 0) print_str("#");
        float v = (float)y / (float)IMG_H;
        float gy_f = v * (float)NF_GRID;
        int gy0 = (int)gy_f;
        if (gy0 >= NF_GRID) gy0 = NF_GRID - 1;
        float ty = gy_f - (float)gy0;

        for (int x = 0; x < IMG_W; x++) {
            float u = (float)x / (float)IMG_W;
            float gx_f = u * (float)NF_GRID;
            int gx0 = (int)gx_f;
            if (gx0 >= NF_GRID) gx0 = NF_GRID - 1;
            float tx = gx_f - (float)gx0;

            float nf[OUT_DIM];
            for (int c = 0; c < OUT_DIM; c++) {
                float c00 = nf_grid[gy0][gx0][c];
                float c10 = nf_grid[gy0][gx0 + 1][c];
                float c01 = nf_grid[gy0 + 1][gx0][c];
                float c11 = nf_grid[gy0 + 1][gx0 + 1][c];
                nf[c] = c00 + (c10 - c00) * tx + (c01 - c00) * ty + (c00 - c10 - c01 + c11) * tx * ty;
            }

            int is_water = (v > horizon_y);
            float sv = is_water ? (horizon_y - (v - horizon_y) * 0.88f) : v;
            float su = u;
            float wave_ripple = 0.0f;
            if (is_water && water_amt > 0.15f) {
                float depth = (v - horizon_y) / (1.0f - horizon_y + 1e-5f);
                wave_ripple = my_sinf(depth * 95.0f + fbm2d(u * 14.0f, depth * 22.0f, 3, 0.6f, seed + 201) * 9.0f);
                su = my_clampf(u + wave_ripple * 0.018f * water_amt * (1.0f - 0.5f * depth), 0.0f, 0.999f);
                sv = my_clampf(sv + wave_ripple * 0.008f * water_amt, 0.01f, horizon_y);
            }
            int sx = (int)(su * (float)(IMG_W - 1));

            float sky_t = my_clampf(sv / (horizon_y + 1e-5f), 0.0f, 1.0f);
            float sky_curve = sky_t * sky_t;
            float r = my_lerp(zen_r, hor_r, sky_curve) + 0.055f * nf[0];
            float g = my_lerp(zen_g, hor_g, sky_curve) + 0.055f * nf[1];
            float b = my_lerp(zen_b, hor_b, sky_curve) + 0.055f * nf[2];

            if (stars_amt > 0.15f && !is_water) {
                float star_cell_x = my_floorf(u * 180.0f);
                float star_cell_y = my_floorf(v * 180.0f);
                float sh = hash2d((int)star_cell_x, (int)star_cell_y, seed + 303);
                if (sh > 0.972f - 0.025f * stars_amt) {
                    float sx_c = (u * 180.0f - star_cell_x) - 0.5f;
                    float sy_c = (v * 180.0f - star_cell_y) - 0.5f;
                    float sd2 = sx_c * sx_c + sy_c * sy_c;
                    float star_b = my_expf_neg(sd2 * 28.0f) * stars_amt * (1.0f - 0.6f * sky_t);
                    r += star_b * 0.95f;
                    g += star_b * 0.95f;
                    b += star_b * 1.05f;
                }
                if (stars_amt > 0.45f) {
                    float neb = fbm2d(u * 3.5f + nf[3], sv * 3.5f + nf[4], 5, 0.7f, seed + 401);
                    float neb_mask = my_smoothstep(0.42f, 0.82f, neb) * stars_amt * (1.0f - 0.4f * sky_t);
                    r += neb_mask * (0.45f + 0.40f * red_acc + 0.25f * nf[0]);
                    g += neb_mask * (0.15f + 0.35f * grn_acc + 0.20f * nf[1]);
                    b += neb_mask * (0.55f + 0.35f * blu_acc + 0.25f * nf[2]);
                }
            }

            if (neon_amt > 0.25f && sv < horizon_y) {
                float wave1 = my_sinf(su * 8.5f + nf[3] * 2.5f + fbm2d(su * 4.0f, sv * 3.0f, 3, 0.5f, seed + 503) * 4.0f);
                float ribbon_y = 0.22f + 0.12f * wave1;
                float dist_rib = my_fabsf(sv - ribbon_y);
                float aur = my_expf_neg(dist_rib * 16.0f) * neon_amt * (1.0f - sky_t * 0.5f);
                float rays = 0.5f + 0.5f * my_sinf(su * 48.0f + nf[4] * 6.0f);
                aur *= (0.45f + 0.55f * rays);
                r += aur * (0.25f + 0.65f * my_clampf(red_acc, 0.0f, 1.0f));
                g += aur * (0.65f + 0.35f * my_clampf(grn_acc, 0.0f, 1.0f));
                b += aur * (0.55f + 0.45f * my_clampf(blu_acc, 0.0f, 1.0f));
            }

            if (orb_amt > 0.15f) {
                float dx = su - orb_x;
                float dy = sv - orb_y;
                float dist = my_sqrtf(dx * dx + dy * dy);
                float glow = my_expf_neg(dist / (orb_rad * 2.2f)) * orb_amt * 0.65f;
                r += glow * (0.75f + 0.25f * warmth);
                g += glow * (0.45f + 0.20f * brightness);
                b += glow * (0.35f - 0.20f * warmth + 0.35f * neon_amt);

                if (dist < orb_rad) {
                    int slice_cut = 0;
                    if ((grid_amt > 0.35f || neon_amt > 0.65f) && sv > orb_y) {
                        float rel_y = (sv - orb_y) / orb_rad;
                        float band = my_fmodf(rel_y * 7.5f, 1.0f);
                        if (band < rel_y * 0.55f) slice_cut = 1;
                    }
                    if (!slice_cut) {
                        float edge = my_smoothstep(orb_rad, orb_rad * 0.88f, dist);
                        float orb_r = (warmth >= -0.2f) ? 1.0f : 0.88f;
                        float orb_g = (warmth >= -0.2f) ? my_lerp(0.35f, 0.92f, 1.0f - (sv - (orb_y - orb_rad)) / (2.0f * orb_rad)) : 0.92f;
                        float orb_b = (warmth >= -0.2f) ? (0.25f + 0.45f * neon_amt) : 0.98f;
                        if (warmth < -0.25f && brightness < -0.2f) {
                            float cr = fbm2d(su * 24.0f, sv * 24.0f, 3, 0.5f, seed + 601);
                            orb_r *= (0.82f + 0.22f * cr);
                            orb_g *= (0.84f + 0.20f * cr);
                            orb_b *= (0.88f + 0.16f * cr);
                        }
                        r = my_lerp(r, orb_r, edge);
                        g = my_lerp(g, orb_g, edge);
                        b = my_lerp(b, orb_b, edge);
                    }
                }
            }

            if (cloud_amt > 0.1f && sv < horizon_y) {
                float cn = fbm2d(su * 5.0f + 0.3f * nf[3], sv * 9.0f, 4, 0.55f, seed + 701);
                float cmask = my_smoothstep(0.48f - 0.18f * cloud_amt, 0.78f, cn) * cloud_amt * (1.0f - 0.3f * sky_t);
                float cr = my_lerp(hor_r, 0.95f, 0.5f + 0.4f * brightness);
                float cg = my_lerp(hor_g, 0.92f, 0.5f + 0.4f * brightness);
                float cb = my_lerp(hor_b, 0.96f, 0.5f + 0.4f * brightness);
                r = my_lerp(r, cr, cmask * 0.65f);
                g = my_lerp(g, cg, cmask * 0.65f);
                b = my_lerp(b, cb, cmask * 0.65f);
            }

            if (mtn_amt > 0.1f) {
                if (sv >= mtn_h1[sx] && sv <= horizon_y) {
                    float m_depth = (sv - mtn_h1[sx]) / (horizon_y - mtn_h1[sx] + 1e-4f);
                    int sx_r = (sx + 6 < IMG_W) ? sx + 6 : IMG_W - 1;
                    int sx_l = (sx - 6 >= 0) ? sx - 6 : 0;
                    float slope = (mtn_h1[sx_r] - mtn_h1[sx_l]) * 18.0f;
                    float rock_tex = fbm2d(su * 14.0f + m_depth * 2.0f, sv * 16.0f, 4, 0.6f, seed + 801);
                    float shade = my_clampf(0.52f + slope * (orb_x > 0.5f ? 1.0f : -1.0f) + (rock_tex - 0.5f) * 0.35f, 0.18f, 0.98f);
                    float mr = 0.14f + 0.14f * my_clampf(warmth, 0.0f, 1.0f) + 0.14f * shade;
                    float mg = 0.15f + 0.10f * my_clampf(brightness, 0.0f, 1.0f) + 0.15f * shade;
                    float mb = 0.26f + 0.12f * my_clampf(-warmth, 0.0f, 1.0f) + 0.20f * shade;
                    float snow_line = 0.26f + 0.28f * my_clampf(-warmth, 0.0f, 1.0f) + 0.12f * (rock_tex - 0.5f);
                    if (m_depth < snow_line) {
                        float snow_blend = my_clampf((snow_line - m_depth) / (snow_line + 1e-4f), 0.0f, 1.0f) * (0.45f + 0.55f * shade);
                        if (warmth > 0.85f && red_acc > 0.85f) {
                            mr = my_lerp(mr, 1.0f, snow_blend);
                            mg = my_lerp(mg, 0.35f, snow_blend);
                            mb = my_lerp(mb, 0.05f, snow_blend);
                        } else {
                            mr = my_lerp(mr, 0.88f, snow_blend * 0.85f);
                            mg = my_lerp(mg, 0.93f, snow_blend * 0.85f);
                            mb = my_lerp(mb, 0.98f, snow_blend * 0.85f);
                        }
                    }
                    float haze = m_depth * m_depth * 0.50f;
                    r = my_lerp(mr, hor_r, haze);
                    g = my_lerp(mg, hor_g, haze);
                    b = my_lerp(mb, hor_b, haze);
                }
                if (sv >= mtn_h2[sx] && sv <= horizon_y) {
                    float m_depth = (sv - mtn_h2[sx]) / (horizon_y - mtn_h2[sx] + 1e-4f);
                    float tex = fbm2d(su * 16.0f, sv * 16.0f, 3, 0.65f, seed + 809);
                    float mr = (0.07f + 0.10f * my_clampf(warmth, 0.0f, 1.0f) + 0.09f * tex);
                    float mg = (0.08f + 0.10f * my_clampf(grn_acc, 0.0f, 1.0f) + 0.09f * tex);
                    float mb = (0.15f + 0.12f * my_clampf(blu_acc, 0.0f, 1.0f) + 0.10f * tex);
                    float haze = m_depth * 0.30f;
                    r = my_lerp(mr, hor_r, haze);
                    g = my_lerp(mg, hor_g, haze);
                    b = my_lerp(mb, hor_b, haze);
                }
            }

            if (city_amt > 0.15f && sv >= city_h[sx] && sv <= horizon_y) {
                int bid = city_bldg_id[sx];
                r = 0.05f + 0.04f * (float)(bid & 3) * 0.25f;
                g = 0.06f + 0.04f * (float)(bid & 3) * 0.25f;
                b = 0.11f + 0.06f * (float)(bid & 3) * 0.25f;

                int wx = (int)(su * 380.0f);
                int wy = (int)(sv * 320.0f);
                float w_frac_x = su * 380.0f - (float)wx;
                float w_frac_y = sv * 320.0f - (float)wy;
                if (w_frac_x > 0.22f && w_frac_x < 0.78f && w_frac_y > 0.22f && w_frac_y < 0.78f) {
                    float wh = hash2d(wx, wy, seed + 907 + bid);
                    if (wh > 0.52f) {
                        if (neon_amt > 0.45f && (wh > 0.82f)) {
                            if (((wx + bid) & 1) == 0) {
                                r = 0.98f; g = 0.20f; b = 0.88f;
                            } else {
                                r = 0.15f; g = 0.92f; b = 0.99f;
                            }
                        } else {
                            r = 0.95f; g = 0.82f; b = 0.48f;
                        }
                    }
                }
            }

            if (forest_amt > 0.15f && sv >= tree_h[sx] && sv <= horizon_y) {
                float td = (sv - tree_h[sx]) / (horizon_y - tree_h[sx] + 1e-4f);
                r = 0.03f + 0.04f * td;
                g = 0.08f + 0.12f * my_clampf(grn_acc + 0.4f, 0.0f, 1.0f) * (1.0f - 0.5f * td);
                b = 0.06f + 0.06f * td;
            }

            if (is_water) {
                float depth = (v - horizon_y) / (1.0f - horizon_y + 1e-5f);
                if (grid_amt > 0.35f) {
                    float bg_r = 0.06f + 0.08f * depth;
                    float bg_g = 0.02f;
                    float bg_b = 0.14f + 0.12f * depth;
                    float persp_x = (u - 0.5f) / (depth + 0.06f);
                    float grid_x = my_fabsf(my_fmodf(persp_x * 4.5f + 100.0f, 1.0f) * 2.0f - 1.0f);
                    float grid_y = my_fabsf(my_fmodf(1.8f / (depth + 0.05f), 1.0f) * 2.0f - 1.0f);
                    float line = 0.0f;
                    if (grid_x < 0.09f) line = 1.0f - grid_x / 0.09f;
                    if (grid_y < 0.11f) {
                        float ly = 1.0f - grid_y / 0.11f;
                        if (ly > line) line = ly;
                    }
                    float glow_line = line * (1.0f - 0.25f * depth);
                    r = my_lerp(r * 0.35f + bg_r, 0.98f, glow_line);
                    g = my_lerp(g * 0.35f + bg_g, 0.20f + 0.55f * (1.0f - depth), glow_line);
                    b = my_lerp(b * 0.35f + bg_b, 0.95f, glow_line);
                } else if (water_amt > 0.15f) {
                    float wr = 0.04f + 0.08f * warmth;
                    float wg = 0.12f + 0.14f * grn_acc;
                    float wb = 0.22f + 0.20f * blu_acc;
                    float fresnel = 0.30f + 0.45f * depth;
                    r = my_lerp(r, wr, fresnel);
                    g = my_lerp(g, wg, fresnel);
                    b = my_lerp(b, wb, fresnel);

                    if (orb_amt > 0.2f) {
                        float dx_orb = my_fabsf(u - orb_x);
                        float path_w = 0.03f + 0.14f * depth;
                        if (dx_orb < path_w && wave_ripple > 0.25f) {
                            float spec = (1.0f - dx_orb / path_w) * (wave_ripple - 0.25f) * orb_amt;
                            r += spec * (0.85f + 0.2f * warmth);
                            g += spec * 0.65f;
                            b += spec * (0.45f + 0.4f * neon_amt);
                        }
                    }
                } else {
                    float gn = fbm2d(u * 12.0f, depth * 12.0f, 4, roughness, seed + 1009);
                    float tr = 0.18f + 0.35f * my_clampf(warmth, 0.0f, 1.0f) + 0.15f * gn;
                    float tg = 0.18f + 0.30f * my_clampf(grn_acc, 0.0f, 1.0f) + 0.12f * gn;
                    float tb = 0.15f + 0.35f * my_clampf(-warmth, 0.0f, 1.0f) + 0.12f * gn;
                    r = my_lerp(hor_r, tr, 0.45f + 0.55f * depth);
                    g = my_lerp(hor_g, tg, 0.45f + 0.55f * depth);
                    b = my_lerp(hor_b, tb, 0.45f + 0.55f * depth);
                }
            }

            if (abst_amt > 0.15f) {
                float fn1 = fbm2d(u * 6.0f + nf[0] * 2.5f, v * 6.0f + nf[1] * 2.5f, 5, 0.8f, seed + 1201);
                float fn2 = my_sinf(fn1 * 12.56f + nf[2] * 4.0f);
                float ar = 0.5f + 0.5f * my_sinf(fn2 * 3.14f + nf[0] * 3.0f + red_acc * 2.0f);
                float ag = 0.5f + 0.5f * my_sinf(fn2 * 3.14f + nf[1] * 3.0f + grn_acc * 2.0f + 2.09f);
                float ab = 0.5f + 0.5f * my_sinf(fn2 * 3.14f + nf[2] * 3.0f + blu_acc * 2.0f + 4.18f);
                float blend = abst_amt * 0.78f;
                r = my_lerp(r, ar, blend);
                g = my_lerp(g, ag, blend);
                b = my_lerp(b, ab, blend);
            }

            float h_dist = my_fabsf(v - horizon_y);
            float h_bloom = my_expf_neg(h_dist * 18.0f) * 0.18f;
            r += h_bloom * hor_r;
            g += h_bloom * hor_g;
            b += h_bloom * hor_b;

            int bmp_row = (IMG_H - 1) - y;
            int idx = (bmp_row * IMG_W + x) * 3;
            int ir = (int)(my_clampf(r, 0.0f, 1.0f) * 255.0f + 0.5f);
            int ig = (int)(my_clampf(g, 0.0f, 1.0f) * 255.0f + 0.5f);
            int ib = (int)(my_clampf(b, 0.0f, 1.0f) * 255.0f + 0.5f);
            g_pixels[idx + 0] = (unsigned char)ib;
            g_pixels[idx + 1] = (unsigned char)ig;
            g_pixels[idx + 2] = (unsigned char)ir;
        }
    }
    print_str("] 100%\r\n");
}

static void fill_bmp_header(unsigned char *hdr, int w, int h) {
    for (int i = 0; i < 54; i++) hdr[i] = 0;
    int img_size = w * h * 3;
    int file_size = 54 + img_size;
    hdr[0] = 'B'; hdr[1] = 'M';
    hdr[2] = (unsigned char)(file_size & 0xFF);
    hdr[3] = (unsigned char)((file_size >> 8) & 0xFF);
    hdr[4] = (unsigned char)((file_size >> 16) & 0xFF);
    hdr[5] = (unsigned char)((file_size >> 24) & 0xFF);
    hdr[10] = 54;
    hdr[14] = 40;
    hdr[18] = (unsigned char)(w & 0xFF);
    hdr[19] = (unsigned char)((w >> 8) & 0xFF);
    hdr[20] = (unsigned char)((w >> 16) & 0xFF);
    hdr[21] = (unsigned char)((w >> 24) & 0xFF);
    hdr[22] = (unsigned char)(h & 0xFF);
    hdr[23] = (unsigned char)((h >> 8) & 0xFF);
    hdr[24] = (unsigned char)((h >> 16) & 0xFF);
    hdr[25] = (unsigned char)((h >> 24) & 0xFF);
    hdr[26] = 1;
    hdr[28] = 24;
    hdr[34] = (unsigned char)(img_size & 0xFF);
    hdr[35] = (unsigned char)((img_size >> 8) & 0xFF);
    hdr[36] = (unsigned char)((img_size >> 16) & 0xFF);
    hdr[37] = (unsigned char)((img_size >> 24) & 0xFF);
}

