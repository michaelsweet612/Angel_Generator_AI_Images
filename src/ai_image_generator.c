/* ---------------- Lightweight Float & Token Parser for model_weights.txt ---------------- */

static const char* skip_ws_and_comments(const char *p) {
    while (*p) {
        if (*p == ' ' || *p == '\t' || *p == '\r' || *p == '\n') {
            p++;
        } else if (*p == '#') {
            while (*p && *p != '\n') p++;
        } else {
            break;
        }
    }
    return p;
}

static const char* next_token(const char *p, char *tok, int max_tok) {
    p = skip_ws_and_comments(p);
    int i = 0;
    while (*p && *p != ' ' && *p != '\t' && *p != '\r' && *p != '\n') {
        if (i < max_tok - 1) tok[i++] = *p;
        p++;
    }
    tok[i] = '\0';
    return p;
}

static float parse_float(const char *s) {
    float sign = 1.0f;
    if (*s == '-') { sign = -1.0f; s++; }
    else if (*s == '+') { s++; }
    float val = 0.0f;
    while (*s >= '0' && *s <= '9') {
        val = val * 10.0f + (float)(*s - '0');
        s++;
    }
    if (*s == '.') {
        s++;
        float scale = 0.1f;
        while (*s >= '0' && *s <= '9') {
            val += (float)(*s - '0') * scale;
            scale *= 0.1f;
            s++;
        }
    }
    return sign * val;
}

static int parse_int(const char *s) {
    int sign = 1;
    if (*s == '-') { sign = -1; s++; }
    int v = 0;
    while (*s >= '0' && *s <= '9') {
        v = v * 10 + (*s - '0');
        s++;
    }
    return sign * v;
}

