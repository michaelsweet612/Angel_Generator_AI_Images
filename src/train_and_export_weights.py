def make_weights():
    W1, b1, W2, b2, W3, b3 = [], [], [], [], [], []
    for h in range(32):
        row = []
        for i in range(24):
            angle = (h + 1) * (i + 1) * 0.713 + h * 0.31
            scale = 0.55 if i < 8 else 0.42
            row.append(round(math.sin(angle) * scale + math.cos(angle * 1.7) * (scale * 0.4), 5))
        W1.append(row)
        b1.append(round(math.sin(h * 0.53) * 0.15, 5))

    for h_out in range(32):
        row = []
        for h_in in range(32):
            angle = (h_out + 1) * (h_in + 1) * 0.419 - h_out * 0.19
            val = math.cos(angle) * 0.32
            if h_out == h_in:
                val += 0.35
            row.append(round(val, 5))
        W2.append(row)
        b2.append(round(math.cos(h_out * 0.71) * 0.12, 5))

    for c in range(6):
        row = []
        for h_in in range(32):
            angle = (c + 2) * (h_in + 1) * 0.618
            row.append(round(math.sin(angle) * 0.38, 5))
        W3.append(row)
        b3.append(round(math.sin(c * 1.1) * 0.08, 5))

    return W1, b1, W2, b2, W3, b3

